# 类别种子 —— 只给「用途」这一把尺子的六个值，不预设任何物件（那是用户自己的数据）。
#
# 🔴 类别**只装用途**（这东西干嘛用的）。不要往里加体型（大件 / 小玩意儿）
#    或价值档（高 / 中 / 低）—— 那是另外两把尺子，三条理由：
#    ① 类别带 default_lifespan_months 的**预填**语义：「大件」一旦预填 10 年，
#       冰箱（10 年）与床（20 年）就共用一个错的默认值 —— 这是**软兜底**，
#       而预填会改变人填写的行为，与「类别默认年限绝不兜底」是同一条铁律的两个面；
#    ② 类别是**必填 + PROTECT**：两把尺子挤进一个必填下拉，必然出现选不出来的物件
#       （相机：体积小、金额高 —— 既不像「大件」也不像「小玩意儿」）；
#    ③ 类别是四卡与筛选的**统计维度**，混装后任何按类别的数字都不再可解释。
#    ⇒ 价值判断走「按金额排序」，**不落字段**。
#      判据：能排序出来的，不要存成档位；能算出来的，不要存成标签。
#
# ⚠️ 种子里**刻意不给 `default_lifespan_months`**（留空，由用户自己填）。
#    这不是漏写：给一个「空调用 10 年」的通用值，等于系统替他定了年限 ——
#    而空调用几年取决于买的是哪种、放在哪儿、怎么用，个体差异极大。
