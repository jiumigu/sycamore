#       （同高频硬坑⑩「静默给出看着合理的错值」与⑫「把两个数并排念出来」）。
#
#    为什么仍不把它做成状态的第四个值：
#      「坏了的空调，算不算在用件数？」这个问题依旧没有正确答案 ——
#      坏了但还留着（保修期内等师傅）是常态：它该算件数，却不该再按残值计入净值。
#      两个维度拆开才能同时表达这两件事；合成一个下拉，用户随手挑的那个
#      就会变成统计口径（四卡、合计全跟着变）。这正是本项目反复踩的那类坑：
#      **一个字段承担两件事 ⇒ 静默给出看着合理的错值**。
#
#    允许的用法有三种：在列表里看到它、按它筛选、**由它决定净值是否为 0**。
#
# ⚠️ `condition` 是 **MySQL 保留字**：Django 生成的语句一律带反引号、全无问题；
#    但用 mysql CLI 手写查询时必须写成 `` `condition` ``，否则语法错误。
