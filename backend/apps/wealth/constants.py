# 账单项分类规则（v3.58.22，P1-C）
#
# 这一步解决的问题：账单表 wealth_bill_list 只有「是什么分类」
# （category / subcategory / merchant），没有「这笔钱的性质」。
# 于是一批财务规划指标算不出来：
#   · 被动收入覆盖率  ← 需要「主动 / 被动」
#   · 刚性支出覆盖率  ← 需要「固定 / 可变」
#   · 现金流量表五类归集 ← 需要「现金流类别」
# 三者都是「按特征给账单项打标签」，机制同构，故**合并为一张规则表**，
# 只维护一套界面、一套匹配实现（财务系统里「科目映射表」的标准做法）。
#
# 🔴 口径原则（与 P1-B 资产快照一脉相承）：
#   金额是历史事实、**分类是当前视角**。因此分类结果**不落库、实时算**。
#   后果是改一条规则会回溯地改变往期报表 —— 这是**刻意的**，
#   不是 bug：分类是「你怎么看这笔钱」，而不是「这笔钱当时是什么」。
#   同时必须提供「影响预览」，让改动前看得见会动多少，而不是改完才发现。
#
# 🔴 与 wealth_bill_list.necessity 的区别（不要混用）：
#   necessity（必要 / 可选 / 冲动）是**这笔消费该不该花**，刻画自控力；
#   expense_nature（固定 / 可变）是**这笔支出能不能不花**，刻画抗风险能力。
#   实测 necessity 全表非空仅 149 / 6588 行（98% 为空），不可依赖；
