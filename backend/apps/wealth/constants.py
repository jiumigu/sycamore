# 三点估算（PERT）所需的最少样本月数。
# 有记录的月份少于 3 个时 O/M/P 会退化成同一个数，等于假装做了估算 ——
# 此时判「数据不足」，不拿一两个月的支出额冒充稳态基准。
PERT_MIN_MONTHS = 3

# PERT 三点估算的权重：E = (O + 4M + P) ÷ 6。
# 4 倍权重压在「最可能值」上，两端各 1 倍 —— 这是 PERT 的经典配比，
# 含义是「中位数比极值可信 4 倍」，同时仍让极端月对结果有影响。
# ⚠️ 权重和必须等于分母，改配比要同时改这两个数，否则期望值会系统性偏移。
