# ── L1 价值归因枚举（单一真源；redemption 一律从此处导入，不得再重复定义）──
# 命名口径（用户 2026-09-18 拍板，v3.58.10）：诸词统一回答「这段时间换回了什么」，
# 都是口语可直说、**不需要括号注解**的二字词。
#   旧：投向(为自己) / 维持(生存运营) / 外部(为他人/牛马) / 流失(空转消耗)
#   新：成长        / 关系            / 维持            / 谋生              / 流失
# 旧词的病灶：「外部」是唯一的方位/关系词（另三个回答"干了什么"，它回答"属于谁"），
# 且「投向」孤立不成词（中文里必须带宾语）；注解本身的存在就说明正名不够自解释。
# 「关系」是 v3.58.11 补上的**第五格**：社交换回的是人与人的联结，
# 既不是能力（成长）、不是钱（谋生）、也不是"不出问题"（维持），硬塞任何一格都别扭。
#   成长 = 换回能力   关系 = 换回联结   维持 = 换回运转   谋生 = 换回钱   流失 = 换回空
#
